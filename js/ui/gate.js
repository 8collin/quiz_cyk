/**
 * Шлюз «ПРОДОЛЖИТЬ» — экран, который заставляет коснуться страницы.
 *
 * Браузер не даёт звучать документу, по которому ни разу не коснулись, а
 * джингл прилетает по realtime — то есть без всякого участия хозяина
 * телефона. Игрок, у которого сессия восстановилась из localStorage,
 * попадал прямо в игру, ни разу ничего не нажав, и весь раунд сидел молча:
 * в консоли оставалось «Звук не проигран: default play() failed because
 * the user didn't interact with the document first».
 *
 * Отсюда экран: пока по нему не нажали, игры не видно, а нажатие снимает
 * запрет (Quiz.audio.unlock).
 *
 * Показывается он НЕ всегда, а только когда касания ещё не было: вошедший
 * через форму уже нажал «Войти», и звук ему разблокировал тот же самый
 * `armUnlock`. Лишний экран после ручного входа был бы платой ни за что.
 * Признак — `Quiz.audio.unlocked`, а не «пришли мы из формы или нет»:
 * разблокировка и есть то, ради чего всё это, и спрашивать надо именно её.
 */
Quiz.ui = Quiz.ui || {};
Quiz.ui.gate = {
    bind: function () {
        Quiz.dom.on('btn-gate', 'click', function () {
            // Синхронно, без единого await до этой строки: разрешение
            // выдаётся под касание и до первой же паузы не доживает.
            // Обычно запрет уже снят перехватывающим слушателем из
            // armUnlock — этот вызов на случай, если pointerdown не
            // случился (клавиатура, экзотический браузер).
            Quiz.audio.unlock();
            Quiz.ui.gate.hide();
        });
    },

    /**
     * Нужен ли шлюз этой роли. Ведущий выключен через config, но код для
     * него написан целиком — см. GATE_FOR_ADMIN.
     */
    needed: function (role) {
        if (Quiz.audio.unlocked) return false;
        return role === 'admin' ? Quiz.config.GATE_FOR_ADMIN
                                : Quiz.config.GATE_FOR_PLAYER;
    },

    /**
     * Зовётся при входе в игру. Загрузку не задерживает: состояние тянется
     * под шлюзом, и к нажатию экран уже готов.
     */
    maybeShow: function (role) {
        if (!this.needed(role)) return;
        Quiz.dom.toggle('gate', true);
    },

    hide: function () {
        Quiz.dom.toggle('gate', false);
    }
};
