-- ---------------------------------------------------------------------
-- Звуки: таблица, бакет и права.
--
-- Применять после 004_stats.sql.
--
-- До этого джинглы лежали папкой `audio/` рядом со страницей, и любая
-- правка означала доступ к файлам сайта. Теперь файл живёт в Storage,
-- а строка здесь — то, чем его адресуют, как громко играть и можно ли
-- его трогать. Папка `audio/` после переезда не нужна.
--
-- Байты в саму таблицу не кладём. `bytea` через PostgREST приезжает
-- base64 (+33% объёма), целиком до первой ноты, без HTTP-кеша и без
-- range-запросов. Storage — тот же Supabase, и метаданные всё равно
-- остаются строкой в базе.
-- ---------------------------------------------------------------------

-- ---------------------------------------------------------------------
-- Таблица
--
-- `key` — то же самое, чем звук адресуется сегодня: `participant.sound_key`
-- ссылается сюда, а `Quiz.config` называет по имени `intro` и `default`.
-- Внешнего ключа между ними намеренно нет: удалённый звук оставит у
-- игрока висячий ключ, и тот тихо провалится в `default` — ровно то же,
-- что происходило с пропавшим файлом. Для джингла это правильный размен,
-- зато `sound_key` не требует ни миграции данных, ни правки подписок.
--
-- `volume` — микшер этого звука, 0..1. Множитель поверх него — локальный
-- ползунок громкости, который у каждого свой и живёт в localStorage.
-- Итоговое  clip.volume = локальный × sound.volume.
--
-- `is_system` — `intro` и `default`. Они не принадлежат никакому игроку,
-- и без признака панель звуков не смогла бы их показать, когда игроков
-- в базе нет вовсе. Переименовать ключ или удалить такую строку панель
-- не даёт: без `default` игре нечем заменить пропавший джингл.
-- ---------------------------------------------------------------------
create table if not exists public.sound (
    id         uuid        primary key default gen_random_uuid(),
    key        text        not null unique,
    title      text,
    -- Путь объекта в бакете `sounds`. Публичный адрес собирается из него
    -- на клиенте (`getPublicUrl`), поэтому сюда он не пишется: смена
    -- домена проекта не должна означать правку каждой строки.
    --
    -- Отдельная колонка, а не «путь = ключ», по двум причинам, и первая
    -- выяснилась переездом: Storage отвергает в имени объекта всё, кроме
    -- узкого набора ASCII, а ключи здесь — имена игроков, то есть почти
    -- всегда кириллица («Invalid key: Алина.mp3»). Вторая — кеш: бакет
    -- публичный и отдаёт объекты с max-age=3600, так что новый файл на
    -- прежнем пути ещё час не был бы слышен. Поэтому путь генерируется
    -- заново на каждую заливку, см. Quiz.ui.sounds.freshPath.
    path       text        not null,
    volume     real        not null default 1,
    is_system  boolean     not null default false,
    created_at timestamptz not null default now(),

    constraint sound_volume_range check (volume >= 0 and volume <= 1)
);

comment on table public.sound is
    'Джинглы. Файл лежит в бакете sounds, здесь ключ, микшер и признак системного.';

-- Изменение громкости обязано доехать до всех устройств: джингл играет
-- не у того, кто нажал, а у всех сразу. Фильтра по игре у этой таблицы
-- нет, поэтому подписка идёт без него — и событие DELETE с одним
-- первичным ключом доходит как есть, `replica identity full` не нужен.
alter publication supabase_realtime add table public.sound;

-- ---------------------------------------------------------------------
-- Политики таблицы. Читают все вошедшие — ключ и громкость нужны каждому
-- устройству, которое будет этот звук играть. Пишет только ведущий.
-- ---------------------------------------------------------------------
alter table public.sound enable row level security;

create policy sound_select_authenticated on public.sound
    for select to authenticated
    using (true);

create policy sound_admin_all on public.sound
    for all to authenticated
    using (public.is_admin())
    with check (public.is_admin());

-- ---------------------------------------------------------------------
-- Бакет
--
-- Публичный: джингл не секрет, а публичный объект отдаётся без токена и
-- с заголовком кеширования — значит, повторное проигрывание не ходит в
-- сеть, и страница, открытая с диска, тоже его получит. Подписанные
-- ссылки протухают и мешали бы предзагрузке.
--
-- Ограничение размера есть, ограничения по MIME нет: тип, который
-- проставит браузер при загрузке, зависит от системы, и отказ по нему
-- выглядел бы как «файл битый». Что грузить, проверяет панель по
-- расширению — так же, как импорт Excel.
-- ---------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit)
values ('sounds', 'sounds', true, 10485760)
on conflict (id) do update
    set public = excluded.public,
        file_size_limit = excluded.file_size_limit;

-- Чтение публичного бакета идёт мимо RLS, поэтому политика нужна только
-- на запись. Условие то же, что у остальных админских политик.
create policy sound_files_admin_write on storage.objects
    for all to authenticated
    using (bucket_id = 'sounds' and public.is_admin())
    with check (bucket_id = 'sounds' and public.is_admin());
