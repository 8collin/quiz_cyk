-- ---------------------------------------------------------------------
-- Показ таблицы статистики.
--
-- Применять после 003_rls.sql.
--
-- Флаг живёт в строке game по той же причине, что и show_answer: таблица
-- обязана открыться и закрыться на всех экранах разом, а `game` уже
-- входит в публикацию realtime — значит, ни новой подписки, ни опроса не
-- нужно, переключение доедет тем же путём, что и «Ответ».
--
-- Политики трогать не пришлось, и это стоит проверить глазами, а не
-- принять на веру:
--   * game_select_authenticated отдаёт строку game целиком любому
--     вошедшему, так что новую колонку игрок читает без правок;
--   * game_admin_all оставляет запись только ведущему.
-- Прятать сам флаг незачем: он говорит, показана ли таблица, а не что в
-- ней. Данные для неё лежат в answer_log, который и без того читают все.
--
-- Числа таблицы никакой схемы не требуют: это те же строки answer_log,
-- сгруппированные по участнику. Считает их клиент — сумма по десятку
-- строк не повод заводить представление.
-- ---------------------------------------------------------------------
alter table public.game
    add column if not exists show_stats boolean not null default false;

comment on column public.game.show_stats is
    'Показана ли всем таблица статистики. Переключает только ведущий.';
